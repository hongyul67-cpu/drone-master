/* ── 도구의 드론 그림을 그대로 부른다 ──
   figHtml() 은 innerHTML 로 꽂히므로, 다음 프레임이면 상자가 화면에 있다.
   그때 mount 해야 크기를 재서 제대로 그려진다. */
var seq = 0;
function drone(parts, spin) {
  var id = 'dkz' + (++seq);
  /* 자리(<div>)를 글자로 돌려주고, 화면에 실제로 붙은 뒤에 드론을 그린다.
     한 프레임 뒤에 찾으면 아직 없다 — 뷰어가 글자를 넣는 때가 그보다 늦다.
     (이것 때문에 드론 그림 자리가 빈 상자로 나왔다.) 붙을 때까지 프레임마다 다시 찾는다. */
  (function look(n) {
    var el = document.getElementById(id);
    if (!el || !window.DroneAnim) {
      // 다시 볼 약속을 둘로 건다 — 화면이 숨겨져 있으면 requestAnimationFrame 이
      // 아예 불리지 않는다(다른 창에 가려 두고 열어 둔 교실 화면이 그렇다).
      if (n < 90) {
        requestAnimationFrame(function () { look(n + 1); });
        setTimeout(function () { look(n + 1); }, 60);
      }
      return;
    }
    if (el.childElementCount) return;      // 이미 그렸다
    try {
      var D = DroneAnim.mount(el, { layout:'pixhawk', caption:'' });
      parts.forEach(function (p) { D.part(p, true); });
      if (spin) D.spin(spin);
    } catch (e) {}
  })(0);
  return '<div id="' + id + '"></div>';
}

